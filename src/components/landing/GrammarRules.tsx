/* ---------- أرقام هندية للترقيم التراثي ---------- */
function arabicNum(n: number): string {
  var map = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩']
  return String(n).split('').map(function (d) { return map[Number(d)] ?? d }).join('')
}

